# -*- coding: utf-8 -*-
"""
الگوهای مشترک تشخیص «آدرس فیزیکی واقعی» — استفاده در هر دو
authority_extractor.py (A3) و trust_extractor.py (T4)، چون هر دو
دقیقاً همین مفهوم را می‌سنجند (هرکدام روی متن متفاوتی: A3 روی صفحه‌ی
«درباره ما»، T4 روی صفحه‌ی فعلی + «تماس با ما»).

یافته‌ی رفع باگ ۱ (ناهماهنگی): این دو فایل قبلاً هرکدام نسخه‌ی
جداگانه‌ی این الگوها را داشتند (ADDRESS_KEYWORD_PATTERN در
authority_extractor.py حتی «نشانی» را نداشت، ولی نسخه‌ی
trust_extractor.py داشت) — یعنی اگر یکی اصلاح می‌شد، دیگری خودبه‌خود
عقب می‌ماند. حالا یک منبع واحد دارند.

یافته‌ی رفع باگ ۲ (false positive): ADDRESS_KEYWORD_PATTERN با «آدرس
ایمیل: ...» یا «آدرس سایت: ...» هم مچ می‌شد، چون فقط دنبال کلمه‌ی
«آدرس»/«نشانی» + هر کاراکتر غیرفاصله‌ی بعدی می‌گشت — این‌ها آدرس
فیزیکی نیستند. حالا یک negative lookahead این موارد را رد می‌کند.
"""

import re

# رد کردن «آدرس ایمیل»، «آدرس وب‌سایت/سایت»، «آدرس اینترنتی»، یا
# چیزی که بلافاصله بعدش خودِ یک ایمیل/URL باشد (مثل "آدرس: foo@bar.com")
_NON_PHYSICAL_ADDRESS_LOOKAHEAD = (
    r"(?!ایمیل|ایمیلی|وب‌?سایت|سایت|اینترنتی|"
    r"https?://|www\.|\S+@)"
)

ADDRESS_KEYWORD_PATTERN = re.compile(
    r"(آدرس|نشانی)\s*[:\-]?\s*" + _NON_PHYSICAL_ADDRESS_LOOKAHEAD + r"[^\s:\-]+"
)

ADDRESS_STRUCTURE_PATTERN = re.compile(r"خیابان|میدان|کوچه|بلوار|پلاک|بزرگراه")

POSTAL_CODE_PATTERN = re.compile(r"\b\d{10}\b")
